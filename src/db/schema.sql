-- ============================================================
-- Mediko Chat API — MySQL schema (replaces the Supabase/Postgres migrations)
-- Loaded automatically by the MySQL container on first start
-- (mounted into /docker-entrypoint-initdb.d). Safe to re-run.
-- ============================================================

SET NAMES utf8mb4;

-- ── Sessions ────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS chat_sessions (
  id              CHAR(36)      NOT NULL PRIMARY KEY,
  created_at      DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  last_active     DATETIME(3)   NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  customer_email  VARCHAR(255)  NULL,
  metadata        JSON          NULL,
  mode            VARCHAR(10)   NOT NULL DEFAULT 'ai',
  channel         VARCHAR(20)   NOT NULL DEFAULT 'widget',
  channel_user_id VARCHAR(255)  NULL,
  assigned_agent  VARCHAR(255)  NULL,
  handoff_at      DATETIME(3)   NULL,
  customer_name       VARCHAR(255) NULL,
  customer_phone      VARCHAR(20)  NULL,
  status              VARCHAR(10)  NOT NULL DEFAULT 'open',
  last_customer_at    DATETIME(3)  NULL,
  last_agent_at       DATETIME(3)  NULL,
  alerted_at          DATETIME(3)  NULL,
  customer_emailed_at DATETIME(3)  NULL,
  agent_seen_at   DATETIME(3)   NULL,
  customer_seen_at DATETIME(3)  NULL,
  INDEX idx_sessions_mode         (mode, last_active),
  INDEX idx_sessions_status       (status, last_customer_at),
  INDEX idx_sessions_channel_user (channel, channel_user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ── Messages ────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS chat_messages (
  id          CHAR(36)     NOT NULL PRIMARY KEY,
  seq         BIGINT       NOT NULL AUTO_INCREMENT,
  session_id  CHAR(36)     NOT NULL,
  role        VARCHAR(16)  NOT NULL,
  content     TEXT         NOT NULL,
  created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  tokens_used INT          NULL,
  meta        JSON         NULL,
  UNIQUE KEY uq_messages_seq (seq),
  INDEX idx_messages_session (session_id, seq),
  CONSTRAINT fk_messages_session FOREIGN KEY (session_id)
    REFERENCES chat_sessions(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ── Keywords ────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS chat_keywords (
  id          CHAR(36)     NOT NULL PRIMARY KEY,
  pattern     VARCHAR(255) NOT NULL,
  search_term VARCHAR(255) NOT NULL,
  category    VARCHAR(64)  NOT NULL DEFAULT 'health',
  active      TINYINT(1)   NOT NULL DEFAULT 1,
  created_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at  DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_keywords_pattern (pattern),
  INDEX idx_keywords_active (active, pattern)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ── Quick replies ───────────────────────────────────────────
CREATE TABLE IF NOT EXISTS chat_quick_replies (
  id         CHAR(36)     NOT NULL PRIMARY KEY,
  label      VARCHAR(255) NOT NULL,
  message    TEXT         NOT NULL,
  sort_order INT          NOT NULL DEFAULT 0,
  active     TINYINT(1)   NOT NULL DEFAULT 1,
  created_at DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_quick_replies_label (label),
  INDEX idx_quick_replies_active (active, sort_order)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

-- ── Settings ────────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS chat_settings (
  `key`      VARCHAR(64)  NOT NULL PRIMARY KEY,
  value      JSON         NOT NULL,
  updated_at DATETIME(3)  NOT NULL DEFAULT CURRENT_TIMESTAMP(3)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

